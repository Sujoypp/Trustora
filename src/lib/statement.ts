import { Amount, usdcDecimalsFor } from '@/onchain-money'
import { CHAIN_ID, type Payment, NETWORK_NAME } from '@/lib/trustora'
import { buildPdf, type PdfLine } from '@/lib/pdf'
import { shortAddress } from '@/lib/format'

export interface StatementRow {
  date: string
  status: string
  direction: string
  counterparty: string
  /** Signed decimal USDC, for example "-12.5". */
  amount: string
  route: string
  note: string
  txHash: string
  block: string
}

const plainUsdc = (raw: bigint) => Amount.fromRaw(raw, usdcDecimalsFor(CHAIN_ID)).toString()

export function buildRows(payments: Payment[]): StatementRow[] {
  return payments.map((p) => {
    const other = p.direction === 'received' ? p.sender : p.recipient
    const sign = p.direction === 'received' ? '' : p.direction === 'sent' ? '-' : ''
    return {
      date: new Date(p.timestamp * 1000).toISOString(),
      status: p.status === 'confirmed' ? 'Confirmed' : 'Pending',
      direction: p.direction === 'received' ? 'Received' : p.direction === 'sent' ? 'Sent' : 'Self',
      counterparty: other,
      amount: `${sign}${plainUsdc(p.amountRaw)}`,
      route: p.rail === 'native' ? 'Native' : 'ERC-20',
      note: p.note,
      txHash: p.txHash,
      block: p.blockNumber.toString(),
    }
  })
}

/** Quotes a CSV cell and defuses spreadsheet formulas. */
function cell(value: string): string {
  const safe = /^[=+\-@\t\r]/.test(value) && !/^-?\d+(\.\d+)?$/.test(value) ? `'${value}` : value
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe
}

const CSV_HEADERS = ['Date (UTC)', 'Status', 'Direction', 'Counterparty', 'Amount (USDC)', 'Route', 'Note', 'Tx hash', 'Block']

export function statementCsv(rows: StatementRow[]): string {
  const lines = [CSV_HEADERS.map(cell).join(',')]
  for (const r of rows) {
    lines.push(
      [r.date, r.status, r.direction, r.counterparty, r.amount, r.route, r.note, r.txHash, r.block].map(cell).join(','),
    )
  }
  return lines.join('\r\n')
}

const fit = (text: string, width: number) => (text.length > width ? `${text.slice(0, width - 3)}...` : text.padEnd(width))
const fitRight = (text: string, width: number) => text.slice(0, width).padStart(width)

export function statementPdf(rows: StatementRow[], payments: Payment[], address: string): Blob {
  let received = 0n
  let sent = 0n
  for (const p of payments) {
    if (p.direction === 'received') received += p.amountRaw
    else if (p.direction === 'sent') sent += p.amountRaw
  }

  const header: PdfLine = {
    text: `${fit('DATE (UTC)', 17)} ${fit('TYPE', 9)} ${fit('COUNTERPARTY', 24)} ${fitRight('USDC', 16)} ${fit('ROUTE', 7)} ${fit('NOTE', 30)} ${fit('TX', 16)}`,
    font: 'mono',
    size: 8,
    gap: 4,
    color: [0.35, 0.2, 0.7],
  }

  const lines: PdfLine[] = [
    { text: 'TRUSTORA | UNIFIED TRUST', font: 'bold', size: 18, color: [0.35, 0.2, 0.7] },
    { text: 'Account statement', font: 'bold', size: 12, gap: 6 },
    { text: `Wallet: ${address}`, font: 'mono', size: 9 },
    { text: `Network: ${NETWORK_NAME}`, size: 9 },
    { text: `Generated: ${new Date().toISOString().replace('T', ' ').slice(0, 19)} UTC`, size: 9, gap: 6 },
    { text: `Total received: ${plainUsdc(received)} USDC    Total sent: ${plainUsdc(sent)} USDC    Payments: ${rows.length}`, font: 'bold', size: 10, gap: 10 },
    header,
  ]

  for (const r of rows) {
    lines.push({
      text: `${fit(r.date.replace('T', ' ').slice(0, 16), 17)} ${fit(r.direction, 9)} ${fit(shortAddress(r.counterparty), 24)} ${fitRight(r.amount, 16)} ${fit(r.route, 7)} ${fit(r.note || '-', 30)} ${fit(r.txHash.slice(0, 14), 16)}`,
      font: 'mono',
      size: 8,
    })
  }
  if (rows.length === 0) lines.push({ text: 'No payments in this statement.', size: 10 })
  lines.push({ text: `Generated by Trustora from public ${NETWORK_NAME} data. Not a financial record.`, size: 8, color: [0.45, 0.43, 0.55] })

  return buildPdf(lines, { landscape: true, repeat: [header] })
}
